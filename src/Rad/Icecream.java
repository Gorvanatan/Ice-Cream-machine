    private void ConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConfirmActionPerformed
        Label.setText("Your ice Cream is " + Flavour.getSelectedItem() + " with " + Topping1.getSelectedItem() + " & " + Syrup.getSelectedItem());

        if (balance >= cost) {
            if (productIcecream[iceCreamIndex - 1] > 0) {
                if (producttopping[toppingsIndex - 1] > 0) {
                    if (productsyrup[syrupIndex - 1] > 0) {
                        balance -= cost;
                        productIcecream[iceCreamIndex - 1]--;
                        producttopping[toppingsIndex - 1]--;
                        productsyrup[syrupIndex - 1]--;
                        Show.setText("" + balance / 100);
                        cost = 0;
                        Cost.setText("" + cost / 100);
                        stockupdate();
                        JOptionPane.showMessageDialog(null, "Your change is " + balance / 100);
                        balance = 0;
                        Show.setText("0");
                        tencenCounter = 0;
                        twencenCounter = 0;
                        fiftycenCounter = 0;
                        oneeurCounter = 0;
                        twoeurCounter = 0;
                        Flavour.setSelectedIndex(0);
                        Topping1.setSelectedIndex(0);
                        Syrup.setSelectedIndex(0);

                    } else {
                        JOptionPane.showMessageDialog(null, "Syrup is not in stock please choose another!");
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "Toppings are not in stock please choose another!");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Ice Cream not in stock Please select another flavour!");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Not enough Money!");
        }

        // TODO add your handling code here:

    }//GEN-LAST:event_ConfirmActionPerformed

