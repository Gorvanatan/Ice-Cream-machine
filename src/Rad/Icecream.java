    private void CardActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CardActionPerformed
         JOptionPane.showMessageDialog(null, "Paid by card!");
        
            if (productIcecream[iceCreamIndex - 1] > 0) {
                if (producttopping[toppingsIndex - 1] > 0) {
                    if (productsyrup[syrupIndex - 1] > 0) {
                        balance -= cost;
                        productIcecream[iceCreamIndex - 1]--;
                        producttopping[toppingsIndex - 1]--;
                        productsyrup[syrupIndex - 1]--;
                        cost = 0;
                        Cost.setText("" + cost / 100);
                        stockupdate();
                        balance = 0;
                        Flavour.setSelectedIndex(0);
                        Topping1.setSelectedIndex(0);
                        Syrup.setSelectedIndex(0);

                    } else {
                        JOptionPane.showMessageDialog(null, "Syrup is not in stock please choose another!");
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "Toppings are not in stock please choose another!");
                }
            } else {
                JOptionPane.showMessageDialog(null, "Ice Cream not in stock Please select another flavour!");
            }
        
        
    }//GEN-LAST:event_CardActionPerformed

